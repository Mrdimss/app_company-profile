export const locales = ["id", "en"] as const;

export type Locale = (typeof locales)[number];

export const localeCookieName = "girik-locale";

export function isLocale(value: string): value is Locale {
  return locales.includes(value as Locale);
}

export function resolvePreferredLocale(
  savedLocale: string | undefined,
  acceptLanguage: string | null,
): Locale {
  if (savedLocale && isLocale(savedLocale)) return savedLocale;

  const preferences = (acceptLanguage ?? "")
    .split(",")
    .map((preference) => {
      const [tag, quality] = preference.trim().toLowerCase().split(";q=");
      return {
        tag,
        quality: quality ? Number.parseFloat(quality) : 1,
      };
    })
    .filter((preference) => preference.tag && preference.quality > 0)
    .sort((left, right) => right.quality - left.quality);

  for (const { tag } of preferences) {
    if (tag.startsWith("id")) return "id";
    if (tag.startsWith("en")) return "en";
  }

  return "id";
}

export function getLocaleFromPath(pathname: string): Locale {
  const firstSegment = pathname.split("/")[1];
  return isLocale(firstSegment) ? firstSegment : "id";
}

export function localePath(locale: Locale, pathname: string) {
  const pathWithoutLocale = pathname.replace(/^\/(id|en|en-US)(?=\/|$)/, "") || "/";
  return `/${locale}${pathWithoutLocale === "/" ? "" : pathWithoutLocale}`;
}

export function localeHref(locale: Locale, pathname: string, search = "") {
  const query = search ? `?${search.replace(/^\?/, "")}` : "";
  return `${localePath(locale, pathname)}${query}`;
}

